// Flows on the idle-skipping shelf: theme switch repaints, "Open it" inspects and comes back,
// a drawer row opens its book, reduced motion shows the card at once. Screenshots as proof.
import { chromium } from 'playwright';
import fs from 'node:fs';
const OUT = 'C:/portfolio-gabriel/qa/libnews-repair';
const b = await chromium.launch({ args: ['--enable-webgl', '--ignore-gpu-blocklist', '--use-angle=swiftshader'] });
const r = {};
const errors = [];
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on('pageerror', (e) => errors.push(e.message));
await p.goto('http://localhost:5173/library', { waitUntil: 'load' });
await p.waitForSelector('.library--ready', { timeout: 60000 });
await p.waitForTimeout(3000);
await p.click('[aria-label="Switch to dark mode"]');
await p.waitForTimeout(2500);
await p.screenshot({ path: `${OUT}/flow-theme-dark.png` });
r.themeDark = await p.evaluate(() => document.documentElement.dataset.theme);
await p.click('.library__inspect');
await p.waitForFunction(() => document.querySelector('.library')?.classList.contains('library--focused'), null, { timeout: 30000 });
await p.waitForTimeout(3500);
await p.screenshot({ path: `${OUT}/flow-open-it.png` });
r.inspectUrl = p.url();
await p.click('.library__back');
await p.waitForFunction(() => !document.querySelector('.library')?.classList.contains('library--focused'), null, { timeout: 30000 });
r.backUrl = p.url();
await p.waitForTimeout(2000);
await p.click('.library__crumb .library__index-toggle');
await p.waitForTimeout(900);
await p.locator('.library__row-main', { hasText: 'Dom Casmurro' }).click();
await p.waitForFunction(() => document.querySelector('.library')?.classList.contains('library--focused'), null, { timeout: 30000 });
await p.waitForTimeout(3500);
r.rowOpenUrl = p.url();
await p.screenshot({ path: `${OUT}/flow-row-open.png` });
await p.close();
const q = await b.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
await q.goto('http://localhost:5173/library', { waitUntil: 'load' });
await q.waitForSelector('.library__title');
r.reducedCardOpacity = await q.evaluate(() => getComputedStyle(document.querySelector('.library__caption-body')).opacity);
r.errors = errors;
console.log(JSON.stringify(r));
fs.writeFileSync(`${OUT}/flows.json`, JSON.stringify(r, null, 2));
await b.close();
