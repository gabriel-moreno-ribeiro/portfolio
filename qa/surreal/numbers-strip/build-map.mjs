// Builds src/components/Home/Numbers/brazilMap.ts from IBGE's official state mesh.
// Sources (downloaded once into ./geo, no runtime fetch):
//   https://servicodados.ibge.gov.br/api/v3/malhas/paises/BR?intrarregiao=UF&formato=application/json&qualidade=minima
//   https://servicodados.ibge.gov.br/api/v1/localidades/estados
// Run: node qa/surreal/numbers-strip/build-map.mjs [tolerance px, default 1]
import fs from 'node:fs';
const here = new URL('./', import.meta.url).pathname;
const topo = JSON.parse(fs.readFileSync(here + 'geo/br-uf.topo.json', 'utf8'));
const estados = JSON.parse(fs.readFileSync(here + 'geo/estados.json', 'utf8'));
const W = 200;                       // viewBox width; the height follows the country
const EPS = Number(process.argv[2] ?? 1);
const SALVADOR = [-38.5108, -12.9714]; // lon, lat

// Mercator by hand (d3-geo is not installed): fine this close to the equator.
const merc = ([lon, lat]) => [lon * Math.PI / 180, -Math.log(Math.tan(Math.PI / 4 + lat * Math.PI / 360))];
const { scale: [sx, sy], translate: [tx, ty] } = topo.transform;
const raw = topo.arcs.map((arc) => { let x = 0, y = 0; return arc.map(([dx, dy]) => merc([(x += dx) * sx + tx, (y += dy) * sy + ty])); });
const all = raw.flat();
const minX = Math.min(...all.map((p) => p[0])), maxX = Math.max(...all.map((p) => p[0]));
const minY = Math.min(...all.map((p) => p[1])), maxY = Math.max(...all.map((p) => p[1]));
const k = (W - 2) / (maxX - minX);
const fit = ([x, y]) => [1 + (x - minX) * k, 1 + (y - minY) * k];
const H = Math.ceil((maxY - minY) * k + 2);

// Douglas-Peucker per arc: neighbours share arcs, so their borders stay glued.
const dp = (pts, eps) => {
  if (pts.length < 3) return pts;
  const [a, b] = [pts[0], pts[pts.length - 1]];
  const len = Math.hypot(b[0] - a[0], b[1] - a[1]);
  let worst = 0, at = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const p = pts[i];
    const d = len ? Math.abs((b[0] - a[0]) * (a[1] - p[1]) - (a[0] - p[0]) * (b[1] - a[1])) / len : Math.hypot(p[0] - a[0], p[1] - a[1]);
    if (d > worst) { worst = d; at = i; }
  }
  return worst <= eps ? [a, b] : [...dp(pts.slice(0, at + 1), eps).slice(0, -1), ...dp(pts.slice(at), eps)];
};
const arcs = raw.map((arc) => {
  const pts = arc.map(fit);
  const closed = Math.hypot(pts[0][0] - pts.at(-1)[0], pts[0][1] - pts.at(-1)[1]) < 1e-9;
  // A closed arc (an island or a state inside another) needs a second anchor to keep its shape.
  const out = closed ? [...dp(pts.slice(0, pts.length >> 1), EPS).slice(0, -1), ...dp(pts.slice((pts.length >> 1) - 1), EPS)] : dp(pts, EPS);
  return out.map(([x, y]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10]);
});
const ring = (ids) => ids.flatMap((i, n) => { const a = i < 0 ? [...arcs[~i]].reverse() : arcs[i]; return n ? a.slice(1) : a; }).slice(0, -1);
const area = (r) => r.reduce((s, p, i) => { const q = r[(i + 1) % r.length]; return s + p[0] * q[1] - q[0] * p[1]; }, 0) / 2;
const centroid = (r) => { let cx = 0, cy = 0; r.forEach((p, i) => { const q = r[(i + 1) % r.length]; const f = p[0] * q[1] - q[0] * p[1]; cx += (p[0] + q[0]) * f; cy += (p[1] + q[1]) * f; }); const a = area(r) * 6; return [cx / a, cy / a]; };
const num = (n) => String(Math.round(n * 10) / 10).replace(/^(-?)0\./, '$1.');
const path = (r) => 'M' + num(r[0][0]) + ' ' + num(r[0][1]) + 'l' + r.slice(1).map((p, i) => num(p[0] - r[i][0]) + ' ' + num(p[1] - r[i][1])).join(' ').replace(/ -/g, '-') + 'z';

const salvador = fit(merc(SALVADOR));
let points = 0;
const states = topo.objects.BRUF.geometries.map((g) => {
  const e = estados.find((x) => String(x.id) === g.properties.codarea);
  const polys = g.type === 'Polygon' ? [g.arcs] : g.arcs;
  // Outer rings only matter here; specks under 1.5 px² (far islands) are dropped.
  const rings = polys.flatMap((poly) => poly.map(ring)).filter((r) => r.length > 2);
  const big = rings.reduce((a, b) => (Math.abs(area(b)) > Math.abs(area(a)) ? b : a));
  const kept = rings.filter((r) => r === big || Math.abs(area(r)) > 1.5);
  points += kept.reduce((s, r) => s + r.length, 0);
  const c = centroid(big);
  return { uf: e.sigla, name: e.nome, d: kept.map(path).join(''), c: [Math.round(c[0] * 10) / 10, Math.round(c[1] * 10) / 10], far: Math.hypot(c[0] - salvador[0], c[1] - salvador[1]) };
});
// Nearest to Salvador first: the order in which word of mouth lights them up. Bahia is where it starts.
states.sort((a, b) => (a.uf === 'BA' ? -1 : b.uf === 'BA' ? 1 : a.far - b.far));

const out = `// Brazil's 26 states and the Federal District as SVG paths, nearest to Salvador first.
// GENERATED by qa/surreal/numbers-strip/build-map.mjs from IBGE's official mesh
// (servicodados.ibge.gov.br/api/v3/malhas/paises/BR?intrarregiao=UF&qualidade=minima),
// Mercator, simplified to ${EPS}px on a ${W}x${H} box. Do not edit by hand.
export const MAP_W = ${W};
export const MAP_H = ${H};
/** Salvador, where the laptops were repaired. */
export const SALVADOR: [number, number] = [${num(salvador[0])}, ${num(salvador[1])}];
export const STATES: { uf: string; name: string; d: string; c: [number, number] }[] = [
${states.map((s) => `  { uf: '${s.uf}', name: '${s.name}', d: '${s.d}', c: [${s.c}] },`).join('\n')}
];
`;
fs.writeFileSync(here + '../../../src/components/Home/Numbers/brazilMap.ts', out);
console.log({ W, H, EPS, states: states.length, points, bytes: out.length, order: states.map((s) => s.uf).join(' ') });
// Rough preview to look at.
fs.writeFileSync(here + 'geo/preview.svg', `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W * 4}" height="${H * 4}" style="background:#fff8f4">${states.map((s) => `<path d="${s.d}" fill="${['AC', 'AM', 'RR', 'AP', 'MS'].includes(s.uf) ? '#fff8f4' : s.uf === 'DF' ? '#999' : '#f0732d'}" stroke="#111" stroke-width=".6" stroke-linejoin="round"/>`).join('')}<circle cx="${salvador[0]}" cy="${salvador[1]}" r="2.2" fill="#111"/></svg>`);
